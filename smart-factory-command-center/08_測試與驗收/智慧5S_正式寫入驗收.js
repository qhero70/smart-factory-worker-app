function 擷取設定值(程式碼, 欄位名稱) {
  const 安全欄名 = 欄位名稱.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const 配對 = 程式碼.match(new RegExp(`${安全欄名}\\s*:\\s*'([^']*)'`));
  if (!配對) throw new Error(`找不到設定欄位：${欄位名稱}`);
  return 配對[1];
}

function 台北時間(日期 = new Date()) {
  return new Intl.DateTimeFormat('sv-SE', {
    timeZone: 'Asia/Taipei', year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false
  }).format(日期);
}

function 台北日期(日期 = new Date()) {
  return 台北時間(日期).slice(0, 10);
}

function 加天數(天數) {
  return 台北日期(new Date(Date.now() + 天數 * 86400000));
}

function 解析回應(文字) {
  const 清理後 = String(文字 || '').trim().replace(/^\uFEFF/, '');
  try { return JSON.parse(清理後); } catch (錯誤) {
    const 配對 = 清理後.match(/^[\w$]+\((.*)\);?$/s);
    if (配對) return JSON.parse(配對[1]);
    throw new Error(`後端回傳不是 JSON：${清理後.slice(0, 160)}`);
  }
}

function 確認成功(資料, 動作) {
  if (!資料 || 資料.ok === false || 資料.success === false || 資料.成功 === false) {
    throw new Error(`${動作}失敗：${String((資料 && (資料.error || 資料.訊息)) || '未知錯誤')}`);
  }
  return 資料;
}

async function 發送請求(網址, 選項, 動作) {
  const 控制器 = new AbortController();
  const 計時器 = setTimeout(() => 控制器.abort(), 40000);
  try {
    const 回應 = await fetch(網址, Object.assign({ redirect: 'follow', signal: 控制器.signal }, 選項));
    const 資料 = 解析回應(await 回應.text());
    if (!回應.ok) throw new Error(`${動作} HTTP ${回應.status}`);
    return 確認成功(資料, 動作);
  } finally {
    clearTimeout(計時器);
  }
}

